#!/usr/bin/env python3
"""Exp48: quotient the finite Exp47 state spaces by observed futures.

The quotient is relative to Exp47's fixed 24 schedules and behavioral
observables. Both its Cartesian state domain and a separately computed
reachable closure from Exp47's documented seed are analyzed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import deque
from fractions import Fraction as F
from pathlib import Path

EXP47_DIR = Path(__file__).resolve().parents[1] / "exp47_h14_state_characterization"
sys.path.insert(0, str(EXP47_DIR))
import exp47_h14_state_characterization as exp47  # noqa: E402

EXP47_RESULT = EXP47_DIR / "h14_exp47_run.json"
EXP47_SHA256 = "a340d939e0ef41ab2090d5efb94492161108894c2275118168720d187b17dfd7"
FORCE_C_CHALLENGER = F(0)
FORCE_K_CHALLENGER = F(3, 2)


def verify_exp47() -> str:
    artifact = json.loads(EXP47_RESULT.read_text(encoding="utf-8"))
    digest = artifact.pop("sha256")
    canonical = json.dumps(artifact, sort_keys=True, separators=(",", ":"))
    actual = hashlib.sha256(canonical.encode()).hexdigest()
    if digest != EXP47_SHA256 or actual != digest:
        raise ValueError("Exp47 canonical artifact hash does not match the pinned value")
    return digest


def reachable_closure(seed: exp47.State) -> set[exp47.State]:
    """Reachability under all C/K choices, each realizable by a query score."""
    seen = {seed}
    pending = deque([seed])
    while pending:
        state = pending.popleft()
        for challenger in (FORCE_C_CHALLENGER, FORCE_K_CHALLENGER):
            successor, _ = exp47.transition(state, challenger)
            if successor not in seen:
                seen.add(successor)
                pending.append(successor)
    return seen


def representation_key(state: exp47.State) -> tuple:
    return (state.reinforcement_count, state.association, state.link, state.recency_age)


def quotient(states: set[exp47.State] | list[exp47.State]) -> dict:
    groups: dict[tuple, list[exp47.State]] = {}
    for state in states:
        groups.setdefault(exp47.state_signature(state), []).append(state)

    classes = []
    for signature, members in groups.items():
        members.sort(key=representation_key)
        encoded_signature = json.dumps(signature, separators=(",", ":"))
        class_id = hashlib.sha256(encoded_signature.encode()).hexdigest()
        classes.append({
            "class_id": class_id,
            "member_count": len(members),
            "members": [exp47.encode(member) for member in members],
        })
    classes.sort(key=lambda item: item["class_id"])

    witnesses = []
    for group in classes:
        if group["member_count"] > 1:
            first, second = group["members"][:2]
            witnesses.append({
                "state_a": first,
                "state_b": second,
                "representation_distinguishes_pair": first != second,
                "observations_equivalent_for_all_probe_schedules": True,
            })
            if len(witnesses) == 5:
                break

    return {
        "represented_tuple_count": len(states),
        "observational_class_count": len(groups),
        "compression_possible_for_this_protocol": len(groups) < len(states),
        "tuple_states_strictly_finer_than_observational_quotient": len(groups) < len(states),
        "equivalent_distinct_state_witness_count_reported": len(witnesses),
        "equivalent_distinct_state_witnesses": witnesses,
        "class_member_counts": sorted(len(members) for members in groups.values()),
        "classes": classes,
    }


def run() -> dict:
    exp47_hash = verify_exp47()
    cartesian = exp47.all_states()
    seed, seed_history = exp47.construct_history(F(0), 3)
    reachable = reachable_closure(seed)
    cartesian_quotient = quotient(cartesian)
    reachable_quotient = quotient(reachable)

